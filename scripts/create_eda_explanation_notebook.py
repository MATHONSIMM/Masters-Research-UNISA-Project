    "## 13. Preliminary VaR Estimates\n\n"
    "The notebook closes with a first, deliberately simple calculation of **Value-at-Risk (VaR)** — the "
    "central quantity this entire dissertation is built around. VaR answers a specific, practically "
    "important question: *\"over a given horizon (here, one trading day) and at a given confidence level "
