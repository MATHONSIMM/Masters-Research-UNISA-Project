cells.append(md(
    "## 10. Stationarity Tests\n\n"
    "**Stationarity** is a property of a time series: a series is (weakly) stationary if its mean, "
    "variance, and autocorrelation structure do not change over time — the series looks, statistically, "
    "\"the same\" in any window a researcher might choose to look at. This matters enormously in "
    "practice because almost every statistical and machine learning model implicitly assumes the "
    "patterns it learns from historical data will continue to hold in the future; fitting a model to a "
    "**non-stationary** series (like a raw, trending price) risks learning a pattern — such as \"prices "
    "always go up\" — that is really just an artefact of the particular historical window chosen, not a "
    "durable statistical property.\n\n"
    "Two complementary tests are run here, deliberately using **opposite null hypotheses**, so that "
    "agreement between them is much stronger evidence than either test alone.\n\n"
    "**The Augmented Dickey-Fuller (ADF) test** has the null hypothesis $H_0$: *\"the series has a unit "
    "root\"* — a technical way of saying the series is **non-stationary**, prone to wandering away from "
    "any fixed level permanently rather than reverting back to it. A small p-value here counts as "
    "evidence *against* non-stationarity, i.e. evidence *for* stationarity.\n\n"
    "**The KPSS test** flips the null hypothesis around: $H_0$: *\"the series is stationary.\"* A small "
    "p-value here would count as evidence *against* stationarity.\n\n"
    "**Reading the output.** Every one of the ten log-return series produces an ADF p-value "
    "indistinguishable from zero (rejecting the unit-root null decisively, in favour of stationarity) "
    "and a KPSS p-value that fails to reject its own stationarity null (reported as 0.100 for eight of "
    "the ten assets, the maximum p-value the specific KPSS implementation used here reports, and 0.081 "
    "for NVIDIA — still comfortably above the conventional 0.05 threshold). Because the two tests start "
    "from opposite assumptions and arrive at the same conclusion, the finding is unambiguous: **daily "
    "log returns are stationary**, a property statisticians denote **I(0)**, meaning \"integrated of "
    "order zero,\" or equivalently \"already stationary without needing to be differenced.\" This is an "
    "important, reassuring green light for every model built later in this dissertation, since none of "
    "them would be statistically valid to fit directly on a non-stationary input series without further "
    "transformation first."
))

