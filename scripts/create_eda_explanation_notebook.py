    "  bell-shaped distribution with the same basic shape as Normal but explicitly fatter tails, "
    "  controlled by a **degrees-of-freedom** parameter: fewer degrees of freedom means fatter tails, "
    "  and a very large number of degrees of freedom makes the Student-t distribution converge back to "
    "  Normal. The code chooses the degrees of freedom directly from each asset's own *measured* excess "
    "  kurtosis (`dof = 6 / (kurtosis/3 + 1)`, floored at 4), so that an asset with fatter empirically-"
    "  observed tails automatically receives a fatter-tailed Student-t assumption — a direct, "
    "  quantitative response to the Jarque-Bera findings of Section 6.\n"
