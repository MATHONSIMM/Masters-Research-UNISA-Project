    "  sample's own mean $\\mu$ and standard deviation $\\sigma$, and uses the Normal distribution's own "
    "  quantile function to find the cutoff: $\\text{VaR} = -(\\mu + \\sigma \\cdot z_\\alpha)$, where "
    "  $z_\\alpha$ is the point below which only $\\alpha$ of the Normal distribution's probability "
    "  mass falls (for example $z_{0.05} \\approx -1.645$).\n"
